import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

// Django REST API работает на http://127.0.0.1:8000/api/
// Проксируем запросы в dev-режиме, чтобы не думать про CORS
export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    proxy: {
      '/api': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
      },
    },
  },
  build: {
    rollupOptions: {
      output: {
        // Вся сборка складывалась в один файл на мегабайт, который браузер
        // обязан был скачать И РАСПАРСИТЬ целиком до первой отрисовки —
        // именно парсинг давал основную часть заблокированного потока.
        //
        // Теперь библиотеки разнесены по отдельным файлам. Выигрыш не только
        // в параллельной загрузке: куски, которые нужны не сразу (three),
        // подтягиваются после первого кадра, а при повторных заходах
        // неизменившиеся библиотеки берутся из кэша браузера — правка
        // своего кода больше не заставляет качать React и GSAP заново.
        manualChunks(id) {
          if (!id.includes('node_modules')) return undefined;

          // Самая тяжёлая библиотека проекта. Нужна только черепу, который
          // теперь грузится лениво (см. App.jsx), поэтому в первый кадр
          // этот кусок не попадает вовсе.
          if (id.includes('/three/')) return 'three';

          // Анимации нужны сразу: на них построены все переходы между
          // этажами, поэтому кусок грузится вместе с основным кодом.
          if (id.includes('/gsap/')) return 'gsap';

          // Переводы и их подгрузка
          if (id.includes('i18next')) return 'i18n';

          // scheduler обязан лежать здесь же: его тянет react-dom, а
          // react-router из vendor тянет сам react. Если scheduler попадает
          // в vendor, куски начинают ссылаться друг на друга по кругу
          // (vendor -> react -> vendor) и браузер не может загрузить их
          // параллельно — Vite ругается на это при сборке.
          if (
            id.includes('/react/') ||
            id.includes('/react-dom/') ||
            id.includes('/scheduler/')
          ) {
            return 'react';
          }

          return 'vendor';
        },
      },
    },
    // Порог предупреждения: после разделения самый крупный кусок — three,
    // и он заведомо больше стандартных 500 кБ. Ругань в консоли сборки на
    // это уже не полезна, реальные размеры смотрим в отчёте Vite.
    chunkSizeWarningLimit: 700,
  },
});
